add_h2("5.3  Core Search Flow (pseudocode)")
add_code([
    "def search(sentence, opts):",
    "    prompt  = system_rules + schema_and_vocab + sentence      # never the data",
    "    reply   = llm.chat(prompt, response_format=per-provider)   # NVIDIA: prompted JSON",
    "    sql     = parse_json(reply).sql                            # enable_thinking=false",
    "    tree    = sqlglot.parse_one(sql)",
    "    assert  single SELECT parent_asin FROM shirts;             # else reject",
    "    forbid  joins, subqueries, mutations, unknown cols, extra functions",
    "    sql     = normalize_color_tokens(tree)                     # exact pipe match",
    "    sql     = map_pattern_aliases(tree)",
    "    asins   = duckdb.execute(sql, on=shirts_master.parquet,",
    "                            locked_settings, timeout=T)",
    "    ranked  = sort(all_matches, by=[price_tier, bayesian(r,n,R,20), n])",
    "    cards   = top_k(ranked)",
    "    return  cards, applied_constraints                         # empty stays empty",
])
add_h2("5.4  Key Implementation Decisions")
add_bullet("NVIDIA's endpoint does not honour response-format guarantees the same "
           "way OpenAI/OpenRouter do, so the adapter uses prompted JSON plus strict "
           "local parsing for Nemotron (with enable_thinking=false so the SQL JSON "
           "arrives inside the output budget), while OpenAI-compatible providers can "
           "use native json_object mode; a settable LLM_JSON_MODE=prompt escape "
           "hatch exists for any model.")
add_bullet("Exact token semantics are enforced by the validator, not the prompt: "
           "even if the model writes LIKE '%black%', the rewrite makes it an exact "
           "pipe-token test, so light blue is never matched as white and gold never "
           "as yellow.")
add_bullet("The uncertainty toggle defaults to including needs_review predictions "
           "(as specified by the catalogue owner) and searches the actual pattern "
           "field - never the uncertain top candidate.")
add_bullet("Empty results stay empty: silently relaxing a shopper's filter would "
           "break the trust contract of the design.")
add_bullet("The .env (real API key) is git-ignored and verified as never staged; "
           "the repository ships .env.example instead.")

