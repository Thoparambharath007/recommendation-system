def set_par(p, text):
    """Replace paragraph text, keeping the first run's formatting."""
    runs = p.runs
    if runs:
        runs[0].text = text
        for r in runs[1:]:
            r.text = ""
    else:
        p.add_run(text)


def replace_in(p, old, new):
    set_par(p, p.text.replace(old, new))


def clone_after(p):
    """Deep-copy paragraph element after p; returns the new Paragraph."""
    new_el = copy.deepcopy(p._p)
    p._p.addnext(new_el)
    return Paragraph(new_el, p._parent)


def fill_student_group(first_idx):
    """Template repeats 4 identical student lines; clone a 5th, then write names."""
    ps = [paras[first_idx + i] for i in range(4)]
    fifth = clone_after(ps[3])
    ps.append(fifth)
    return ps


