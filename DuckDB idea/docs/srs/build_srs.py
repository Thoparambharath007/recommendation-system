add_h2("4.4  Ranking Design")
add_body(
    "Ranking is a total order recomputable by any reviewer. Tier 0 contains "
    "products with an exact historical price; tier 1 contains estimated prices "
    "(labelled). Within a tier, products are ordered by the Bayesian average "
    "b̄ = (r·n + R·m) / (n + m), where r is the product's own average rating, n its "
    "review count, R the catalogue-wide mean rating and m the prior weight of 20 "
    "reviews; rating count breaks ties. Demands such as \"cheapest\" switch to an "
    "explicit price sort, keeping price estimates labelled. All matches are ranked "
    "before the top-k truncation, so the cut never hides a better-ranked product."
)
