def add_body(text, style="Body Text"):
    p = doc.add_paragraph(text, style=style)
    p.paragraph_format.space_after = Pt(6)
    return p

def add_h1(text, page_break=True):
    p = doc.add_paragraph(text, style="Heading 1")
    if page_break:
        p.paragraph_format.page_break_before = True
    return p

def add_h2(text):
    return doc.add_paragraph(text, style="Heading 2")

def add_h3(text):
    return doc.add_paragraph(text, style="Heading 3")

def add_bullet(text):
    return add_body("•  " + text)

def add_code(lines):
    for ln in lines:
        p = doc.add_paragraph()
        r = p.add_run(ln)
        r.font.name = "Consolas"
        r.font.size = Pt(9)
        p.paragraph_format.space_after = Pt(0)

def _tbl_borders(table):
    tblPr = table._tbl.tblPr
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        e = OxmlElement(f"w:{edge}")
        e.set(qn("w:val"), "single")
        e.set(qn("w:sz"), "6")
        e.set(qn("w:color"), "595959")
        borders.append(e)
    tblPr.append(borders)

def add_table(header, rows, font_pt=9):
    t = doc.add_table(rows=1, cols=len(header))
    try:
        t.style = doc.styles["Table Grid"]
    except KeyError:
        _tbl_borders(t)
    for c, txt in zip(t.rows[0].cells, header):
        p = c.paragraphs[0]
        r = p.add_run(txt)
        r.bold = True
        r.font.size = Pt(font_pt)
    for row in rows:
        cells = t.add_row().cells
        for c, txt in zip(cells, row):
            p = c.paragraphs[0]
            r = p.add_run(str(txt))
            r.font.size = Pt(font_pt)
    doc.add_paragraph()
    return t

def add_figure(path, caption, width=6.2):
    doc.add_picture(str(HERE / path), width=Inches(width))
    cap = doc.paragraphs[-1]
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p = add_body(caption)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for r in p.runs:
        r.italic = True
        r.font.size = Pt(9)

